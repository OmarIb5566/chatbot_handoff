"""
Build an Arabic eval set: the English eval questions rendered in Arabic.

    python make_arabic_eval.py                       # 36-question v1 -> eval_set_ar.json
    python make_arabic_eval.py --source eval_set_v2.json --out eval_set_v2_ar.json

Only `question` changes. `id`, `doc`, `expected_answer`, `must_include` and
`type` are copied verbatim, and that is what makes the Arabic run comparable to
the English one - same gold documents, same target strings, so a difference in
retrieval hit rate is attributable to the translation step and nothing else.

The source and destination are arguments rather than constants because there
are now two English sets: the original 36 and the 100-question eval_set_v2.json
that covers all 71 indexed documents. Same builder, same defects below, two
outputs. Defaults are unchanged, so the v1 command above still does what it
always did.

READ THIS BEFORE QUOTING THE NUMBER
-----------------------------------
These questions are machine-generated by qwen3:14b, the same model that then
translates them back on the way into the retriever. A round trip through one
model flatters itself: it will reliably undo its own word choices in a way it
will not reliably undo a real user's. MT-Arabic is also cleaner and more
MSA-flavoured than what someone actually types.

So treat the resulting score as an UPPER BOUND. Every record carries
`"review": "machine"`; when a human has checked and naturalised a question,
change it to `"human"`. eval_arabic.py reports the two subsets separately, and
the human-reviewed row is the only one worth putting in front of anyone.

Two specific defects in the generated set, found by reading it:

  * **It is MSA, not Egyptian.** The `dialect=EGYPTIAN` argument below is
    largely ignored - qwen3:14b returns Modern Standard Arabic regardless
    ("ما المبلغ المدفوع مقدماً الذي..."). So this set does not test dialect
    input at all, even though dialect is the thing users actually type. The
    dialect path does work - the §5.5 questions in the notebook are hand-
    written Egyptian and retrieve correctly - it is just not what these 36
    questions measure.

  * **Domain terms get mistranslated, and RME's abbreviations get mangled.**
    "PM" becomes رئيس الوزراء (Prime Minister) in PCM02-1 and المدير التنفيذي
    (executive manager) in PCM01-4. "Commercial dept" becomes قسم التجارة,
    which returns as "trade department" and is the one retrieval miss in the
    whole run. A glossary pinning RME's terms would fix the generation side;
    on the query side it is a real failure mode, not an artifact, because a
    user may well write قسم التجارة themselves.

Codes are masked during translation (translate.mask_codes), so questions that
quote F-P-CM-01-01 keep it byte-identical. Verified on the v2 set: 0 of 100
questions lost a code, and metadata is copied through untouched.

WHAT THE SAME DEFECTS LOOK LIKE IN eval_set_v2_ar.json
-------------------------------------------------------
Neither of the two v1 mistranslations above recurs verbatim - no رئيس الوزراء,
no قسم التجارة - but the class of failure does, and one item is worse than a
term swap. Acronym survival across the 100, by whether the model kept the Latin
form: VMO, MOM, NCR kept; PM (2), HoD, HR (3) and DE&I (2) all rendered into
Arabic. Most of those are honest translations. Two are not:

  * **PCN01-3** turns "the PM" into المدير التنفيذي, executive manager - the
    same substitution v1 made in PCM01-4.

  * **PFW01-2** is corrupted outright, and this one is not a term swap. The
    English asks how soon Formwork - a department - must meet the PM/CM. The
    Arabic reads "how soon must the SHAPES meet the REQUIREMENTS": الأشكال for
    Formwork, and "meet" re-read as satisfy-a-condition rather than hold-a-
    meeting. Both content words of the question are gone. It cannot retrieve
    its gold document, and a score that counts it is measuring the translator,
    not the retriever.

So the upper-bound warning above holds for v2 with one addition: the ceiling is
not only optimistic, it also carries at least one question that is unanswerable
for reasons no amount of retrieval work would fix. Read PFW01-2 first when
naturalising this set.

Needs Ollama up:  ollama serve
"""
from __future__ import annotations

import sys
from pathlib import Path

# backend/ holds the pipeline; its modules import each other by bare name.
# See paths.add_backend_to_path for why that is worth keeping.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "backend"))


import argparse
import json
import re
import time
from pathlib import Path

import requests

from translate import EGYPTIAN, enable_utf8_stdout, to_arabic

from paths import EVAL_SET as EVAL_EN, EVAL_SET_AR as EVAL_AR

OLLAMA_HOST = "http://localhost:11434"
MODEL = "qwen3:14b"
THINK_RE = re.compile(r"<think>.*?</think>", re.S | re.I)


def _gen(prompt: str) -> str:
    """Same determinism and trace-stripping as the notebook's generator."""
    payload = {
        "model": MODEL, "prompt": prompt, "stream": False,
        "options": {"temperature": 0, "num_predict": -1, "num_ctx": 8192, "seed": 0},
        "think": False,
    }
    r = requests.post(f"{OLLAMA_HOST}/api/generate", json=payload, timeout=1800)
    if r.status_code == 400:          # older Ollama, or the model rejects `think`
        payload.pop("think")
        r = requests.post(f"{OLLAMA_HOST}/api/generate", json=payload, timeout=1800)
    r.raise_for_status()
    return THINK_RE.sub("", r.json()["response"]).strip()


def main(argv: list[str] | None = None) -> None:
    enable_utf8_stdout()
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--source", type=Path, default=EVAL_EN,
                    help="English eval set to translate (default: eval_set.json)")
    ap.add_argument("--out", type=Path, default=EVAL_AR,
                    help="where to write the Arabic set (default: eval_set_ar.json)")
    ap.add_argument("--limit", type=int, default=0,
                    help="translate only the first N questions, for a smoke run")
    ap.add_argument("--resume", action="store_true",
                    help="keep questions already translated in --out and only do "
                         "the missing ids. A hundred questions is ~15 minutes of "
                         "GPU; losing that to one dropped connection is avoidable.")
    args = ap.parse_args(argv)

    eval_set = json.load(open(args.source, encoding="utf-8"))
    if args.limit:
        eval_set = eval_set[:args.limit]

    done: dict[str, dict] = {}
    if args.resume and args.out.exists():
        done = {it["id"]: it for it in json.load(open(args.out, encoding="utf-8"))
                if it.get("question_en")}
        print(f"resuming: {len(done)} already in {args.out.name}")

    out, t0 = [], time.perf_counter()
    for i, item in enumerate(eval_set, 1):
        if item["id"] in done:
            out.append(done[item["id"]])
            continue
        ar = to_arabic(item["question"], _gen, dialect=EGYPTIAN)
        rec = dict(item)
        rec["question"] = ar
        rec["question_en"] = item["question"]
        # Always "machine", even if the English record said otherwise: this
        # question has just been through MT and nobody has read it yet.
        rec["review"] = "machine"
        out.append(rec)
        print(f"[{i:>3}/{len(eval_set)}] {item['id']}")
        print(f"      {item['question']}")
        print(f"   -> {ar}")
        # Written every turn, not at the end. See --resume.
        args.out.write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")

    args.out.write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"\nWrote {args.out.name}: {len(out)} questions, all review=machine "
          f"({time.perf_counter() - t0:.0f}s)")


if __name__ == "__main__":
    main()
