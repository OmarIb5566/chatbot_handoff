"""
Build eval_set_ar.json: the 36 eval questions rendered in Egyptian Arabic.

Only `question` changes. `id`, `doc`, `expected_answer`, `must_include` and
`type` are copied verbatim, and that is what makes the Arabic run comparable to
the English one - same gold documents, same target strings, so a difference in
retrieval hit rate is attributable to the translation step and nothing else.

READ THIS BEFORE QUOTING THE NUMBER
-----------------------------------
These questions are machine-generated by qwen3:14b, the same model that then
translates them back on the way into the retriever. A round trip through one
model flatters itself: it will reliably undo its own word choices in a way it
will not reliably undo a real user's. MT-Arabic is also cleaner and more
MSA-flavoured than what someone actually types.

So treat the resulting score as an UPPER BOUND. Every record carries
`"review": "machine"`; when a human has checked and naturalised a question,
change it to `"human"`. eval_arabic.py reports the two subsets separately, and
the human-reviewed row is the only one worth putting in front of anyone.

Two specific defects in the generated set, found by reading it:

  * **It is MSA, not Egyptian.** The `dialect=EGYPTIAN` argument below is
    largely ignored - qwen3:14b returns Modern Standard Arabic regardless
    ("ما المبلغ المدفوع مقدماً الذي..."). So this set does not test dialect
    input at all, even though dialect is the thing users actually type. The
    dialect path does work - the §5.5 questions in the notebook are hand-
    written Egyptian and retrieve correctly - it is just not what these 36
    questions measure.

  * **Domain terms get mistranslated, and RME's abbreviations get mangled.**
    "PM" becomes رئيس الوزراء (Prime Minister) in PCM02-1 and المدير التنفيذي
    (executive manager) in PCM01-4. "Commercial dept" becomes قسم التجارة,
    which returns as "trade department" and is the one retrieval miss in the
    whole run. A glossary pinning RME's terms would fix the generation side;
    on the query side it is a real failure mode, not an artifact, because a
    user may well write قسم التجارة themselves.

Codes are masked during translation (translate.mask_codes), so questions that
quote F-P-CM-01-01 keep it byte-identical.

Needs Ollama up:  ollama serve
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import requests

from translate import EGYPTIAN, enable_utf8_stdout, to_arabic

HERE = Path(__file__).resolve().parent
EVAL_EN = HERE / "eval_set.json"
EVAL_AR = HERE / "eval_set_ar.json"

OLLAMA_HOST = "http://localhost:11434"
MODEL = "qwen3:14b"
THINK_RE = re.compile(r"<think>.*?</think>", re.S | re.I)


def _gen(prompt: str) -> str:
    """Same determinism and trace-stripping as the notebook's generator."""
    payload = {
        "model": MODEL, "prompt": prompt, "stream": False,
        "options": {"temperature": 0, "num_predict": -1, "num_ctx": 8192, "seed": 0},
        "think": False,
    }
    r = requests.post(f"{OLLAMA_HOST}/api/generate", json=payload, timeout=1800)
    if r.status_code == 400:          # older Ollama, or the model rejects `think`
        payload.pop("think")
        r = requests.post(f"{OLLAMA_HOST}/api/generate", json=payload, timeout=1800)
    r.raise_for_status()
    return THINK_RE.sub("", r.json()["response"]).strip()


def main() -> None:
    enable_utf8_stdout()
    eval_set = json.load(open(EVAL_EN, encoding="utf-8"))

    out = []
    for i, item in enumerate(eval_set, 1):
        ar = to_arabic(item["question"], _gen, dialect=EGYPTIAN)
        rec = dict(item)
        rec["question"] = ar
        rec["question_en"] = item["question"]
        rec["review"] = "machine"
        out.append(rec)
        print(f"[{i:>2}/{len(eval_set)}] {item['id']}")
        print(f"     {item['question']}")
        print(f"  -> {ar}")

    EVAL_AR.write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"\nWrote {EVAL_AR.name}: {len(out)} questions, all review=machine")


if __name__ == "__main__":
    main()
